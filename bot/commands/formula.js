/**
 * Kuzmix-MD Command: .formula
 * Category: education
 * Description: Lookup and explain mathematical/scientific formulas
 */

module.exports = {
  name: 'formula',
  aliases: [],
  category: 'education',
  description: 'Lookup and explain mathematical/scientific formulas',
  usage: '.formula quadratic formula derivations',
  example: '.formula quadratic formula derivations',
  permission: 'everyone',

  async execute(ctx) {
    const { sock, msg, from, reply, args, isGroup, isOwner, sender, config, database } = ctx;

    const name = 'formula';
    const desc = 'Lookup and explain mathematical/scientific formulas';
    const syntax = '.formula quadratic formula derivations';
    const example = '.formula quadratic formula derivations';
    const nameUpper = 'FORMULA';

    
    const query = args.join(' ').trim();
    if (!query) {
      return reply(`🎓 *Academic Tutor (.${name})*\n\nUsage: \`${syntax}\`\nExample: \`${example}\``);
    }

    await reply('📚 *Consulting academic knowledge repository...*');
    const { ask, format } = require('../lib/aiHelper');
    try {
      const text = await ask(query, `Task: ${desc}. Format output cleanly for WhatsApp.`);
      return reply(format(text, `KUZMIX AI: ${nameUpper}`));
    } catch (err) {
      console.warn('[AI ERROR]', err.message);
    }

    return reply(
      `╔═════『 *ACADEMIC TUTOR: ${nameUpper}* 』═════\n` +
      `📖 *Topic:* ${query}\n\n` +
      `🎯 *Solution & Explanation:*\n` +
      `The concepts underlying ${query} revolve around foundational mathematical, physical, and scientific principles.\n\n` +
      `╚═══════════════════════════════════════════\n\n` +
      `_${config.watermark}_`
    );

  }
};
